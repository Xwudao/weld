// TestEnumConstName covers the snake_case to CamelCase derivation used for the
// generated constants.
func TestEnumConstName(t *testing.T) {
	t.Parallel()
	cases := map[string]string{
		"draft":       "StatusDraft",
		"in_progress": "StatusInProgress",
		"a1":          "StatusA1",
	}
	for value, want := range cases {
		if got := enumConstName("Status", value); got != want {
			t.Errorf("enumConstName(Status, %q) = %q, want %q", value, got, want)
		}
	}
}

func TestAddEnumWritesDefinitionAndMethods(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	dir := create(t, root)

	result := addEnum(t, dir, "status", "draft", "published", "in_progress")
	if len(result.Operations) == 0 {
		t.Fatal("AddEnum planned no operations")
	}

	definition := readFile(t, filepath.Join(dir, "internal/enums/status.go"))
	for _, want := range []string{
		"package enums",
		"type Status string",
		"StatusDraft",
		`Status = "draft"`,
		"StatusPublished",
		`Status = "published"`,
		"StatusInProgress",
		`Status = "in_progress"`,
	} {
		if !strings.Contains(definition, want) {
			t.Errorf("status.go is missing %q:\n%s", want, definition)
		}
	}
	if strings.Contains(definition, "func (v Status) String()") {
		t.Errorf("the definition file carries generated methods:\n%s", definition)
	}

	generated := readFile(t, filepath.Join(dir, "internal/enums/status_gen.go"))
	if !strings.Contains(generated, "Code generated by weld gen enum; DO NOT EDIT.") {
		t.Errorf("status_gen.go lacks the generated header:\n%s", generated)
	}
	for _, want := range []string{
		"func ParseStatus(raw string) (Status, error)",
		"string(StatusInProgress): StatusInProgress",
	} {
		if !strings.Contains(generated, want) {
			t.Errorf("status_gen.go is missing %q:\n%s", want, generated)
		}
	}

	manifest := mustLoad(t, dir)
	if !manifest.Owns("internal/enums/status.go") || !manifest.Owns("internal/enums/status_gen.go") {
		t.Fatalf("enum files are not recorded: %+v", manifest.Files)
	}
	if drift := manifest.Drift(dir); len(drift) != 0 {
		t.Fatalf("drift after add enum: %+v", drift)
	}
	gofmtCheck(t, dir)
}

func TestAddEnumIsIdempotent(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	dir := create(t, root)
	addEnum(t, dir, "status", "draft", "published")

	definition := readFile(t, filepath.Join(dir, "internal/enums/status.go"))
	generated := readFile(t, filepath.Join(dir, "internal/enums/status_gen.go"))

	result, err := AddEnum(Request{Dir: dir, Catalog: newCatalog()}, "status", []string{"draft", "published", "archived"})
	if err != nil {
		t.Fatalf("second AddEnum: %v", err)
	}
	if len(result.Operations) != 0 {
		t.Fatalf("second AddEnum planned %d operations, want 0", len(result.Operations))
	}
	if len(result.Notes) == 0 {
		t.Fatal("second AddEnum produced no explanation")
	}
	if err := result.Apply(); err != nil {
		t.Fatalf("second Apply: %v", err)
	}
	if readFile(t, filepath.Join(dir, "internal/enums/status.go")) != definition {
		t.Fatal("a repeat add rewrote the definition file")
	}
	if readFile(t, filepath.Join(dir, "internal/enums/status_gen.go")) != generated {
		t.Fatal("a repeat add rewrote the generated file")
	}
}

func TestAddEnumIsDryRunnable(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	dir := create(t, root)

	manifestBefore := readFile(t, filepath.Join(dir, project.ManifestName))
	result, err := AddEnum(Request{Dir: dir, Catalog: newCatalog()}, "status", []string{"draft"})
	if err != nil {
		t.Fatalf("AddEnum: %v", err)
	}
	if len(result.Operations) == 0 {
		t.Fatal("expected a non-empty plan")
	}
	if readFile(t, filepath.Join(dir, project.ManifestName)) != manifestBefore {
		t.Fatal("planning wrote the manifest")
	}
	if _, err := os.Stat(filepath.Join(dir, "internal", "enums")); !os.IsNotExist(err) {
		t.Fatal("planning wrote enum files")
	}
}

func TestAddEnumRejectsDuplicateAndCollidingValues(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	dir := create(t, root)

	for _, tc := range []struct {
		name   string
		values []string
		want   string
	}{
		{"status", nil, "at least one value"},
		{"status", []string{"draft", "draft"}, "repeated"},
		{"status", []string{"a_1", "a1"}, "both map to constant"},
		{"status", []string{"Draft"}, "lower_snake_case"},
	} {
		if _, err := AddEnum(Request{Dir: dir, Catalog: newCatalog()}, tc.name, tc.values); err == nil {
			t.Errorf("AddEnum(%v) succeeded, want an error mentioning %q", tc.values, tc.want)
		} else if !strings.Contains(err.Error(), tc.want) {
			t.Errorf("AddEnum(%v) error = %v, want it to mention %q", tc.values, err, tc.want)
		}
	}
	if _, err := os.Stat(filepath.Join(dir, "internal", "enums")); !os.IsNotExist(err) {
		t.Fatal("a rejected add wrote files")
	}
}

