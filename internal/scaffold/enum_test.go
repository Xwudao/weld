func TestGenEnumsRegeneratesAfterEdit(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	dir := create(t, root)
	addEnum(t, dir, "status", "draft", "published")

	definitionPath := filepath.Join(dir, "internal/enums/status.go")
	edited := strings.Replace(readFile(t, definitionPath),
		"\n)\n",
		"\n\tStatusArchived  Status = \"archived\"\n)\n", 1)
	if err := os.WriteFile(definitionPath, []byte(edited), 0o644); err != nil {
		t.Fatal(err)
	}

	stale, err := CheckEnums(Request{Dir: dir})
	if err != nil {
		t.Fatalf("CheckEnums: %v", err)
	}
	if len(stale) != 1 || !strings.Contains(stale[0], "status_gen.go (stale)") {
		t.Fatalf("CheckEnums = %v, want one stale file", stale)
	}

	result, err := GenEnums(Request{Dir: dir, Catalog: newCatalog()}, false)
	if err != nil {
		t.Fatalf("GenEnums: %v", err)
	}
	if err := result.Apply(); err != nil {
		t.Fatalf("Apply GenEnums: %v", err)
	}
	if generated := readFile(t, filepath.Join(dir, "internal/enums/status_gen.go")); !strings.Contains(generated, "StatusArchived") {
		t.Fatalf("regeneration did not pick up the new value:\n%s", generated)
	}
	if stale, err := CheckEnums(Request{Dir: dir}); err != nil || len(stale) != 0 {
		t.Fatalf("CheckEnums after regeneration = %v, %v", stale, err)
	}

	// A second run is a no-op.
	again, err := GenEnums(Request{Dir: dir, Catalog: newCatalog()}, false)
	if err != nil {
		t.Fatalf("second GenEnums: %v", err)
	}
	if len(again.Operations) != 0 {
		t.Fatalf("second GenEnums planned %d operations, want 0", len(again.Operations))
	}
}

func TestGenEnumsPrunesOrphan(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	dir := create(t, root)
	addEnum(t, dir, "status", "draft")
	addEnum(t, dir, "role", "admin")

	if err := os.Remove(filepath.Join(dir, "internal/enums/role.go")); err != nil {
		t.Fatal(err)
	}

	stale, err := CheckEnums(Request{Dir: dir})
	if err != nil {
		t.Fatalf("CheckEnums: %v", err)
	}
	if len(stale) != 1 || !strings.Contains(stale[0], "role_gen.go (orphan)") {
		t.Fatalf("CheckEnums = %v, want the orphan reported", stale)
	}

	result, err := GenEnums(Request{Dir: dir, Catalog: newCatalog()}, true)
	if err != nil {
		t.Fatalf("GenEnums --prune: %v", err)
	}
	if err := result.Apply(); err != nil {
		t.Fatalf("Apply: %v", err)
	}
	if _, err := os.Stat(filepath.Join(dir, "internal/enums/role_gen.go")); !os.IsNotExist(err) {
		t.Fatalf("prune did not delete the orphan: %v", err)
	}
	if mustLoad(t, dir).Owns("internal/enums/role_gen.go") {
		t.Fatal("prune left the orphan in the manifest")
	}
	if _, err := os.Stat(filepath.Join(dir, "internal/enums/status_gen.go")); err != nil {
		t.Fatalf("prune deleted a live generated file: %v", err)
	}
}

// TestGenEnumsRefusesForeignFile proves a *_gen.go without the generated header
// is never overwritten: the generator owns only what it wrote.
func TestGenEnumsRefusesForeignFile(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	dir := create(t, root)

	if err := os.MkdirAll(filepath.Join(dir, "internal", "enums"), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "internal/enums/status.go"),
		[]byte("package enums\n\ntype Status string\n\nconst StatusDraft Status = \"draft\"\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	foreign := "// mine, not generated\npackage enums\n"
	if err := os.WriteFile(filepath.Join(dir, "internal/enums/status_gen.go"), []byte(foreign), 0o644); err != nil {
		t.Fatal(err)
	}

	if _, err := GenEnums(Request{Dir: dir, Catalog: newCatalog()}, false); err == nil {
		t.Fatal("expected a conflict for a foreign *_gen.go")
	}
	if got := readFile(t, filepath.Join(dir, "internal/enums/status_gen.go")); got != foreign {
		t.Fatalf("the foreign file was modified:\n%s", got)
	}
}

