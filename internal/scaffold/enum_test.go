// TestAddEnumGeneratedProjectBuildsAndTests compiles the enum package and runs a
// generated round-trip test that exercises Parse, JSON and the invalid-value
// failure, so the generated codecs are proven against a real build.
func TestAddEnumGeneratedProjectBuildsAndTests(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	dir := create(t, root)
	addEnum(t, dir, "status", "draft", "published", "in_progress")

	probe := `package enums

import (
	"encoding/json"
	"testing"
)

func TestGeneratedEnum(t *testing.T) {
	if got, err := ParseStatus("in_progress"); err != nil || got != StatusInProgress {
		t.Fatalf("ParseStatus = %v, %v", got, err)
	}
	if _, err := ParseStatus("nope"); err == nil {
		t.Fatal("ParseStatus accepted an unknown value")
	}
	if !StatusDraft.IsValid() {
		t.Fatal("StatusDraft is not valid")
	}
	raw, err := json.Marshal(StatusPublished)
	if err != nil || string(raw) != ` + "`\"published\"`" + ` {
		t.Fatalf("Marshal = %s, %v", raw, err)
	}
	var decoded Status
	if err := json.Unmarshal([]byte(` + "`\"draft\"`" + `), &decoded); err != nil || decoded != StatusDraft {
		t.Fatalf("Unmarshal = %v, %v", decoded, err)
	}
	if err := json.Unmarshal([]byte(` + "`\"bogus\"`" + `), &decoded); err == nil {
		t.Fatal("Unmarshal accepted an unknown value")
	}
}
`
	if err := os.WriteFile(filepath.Join(dir, "internal/enums/enum_probe_test.go"), []byte(probe), 0o644); err != nil {
		t.Fatal(err)
	}
	if !buildAndTestGeneratedProject(t, dir) {
		t.Skip("cannot resolve the generated project's dependencies (network/module cache unavailable)")
	}
}
