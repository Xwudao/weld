// addEnum plans and applies `weld add enum <name> <value>...`.
func addEnum(t *testing.T, dir, name string, values ...string) *Result {
	t.Helper()
	result, err := AddEnum(Request{Dir: dir, Catalog: newCatalog()}, name, values)
	if err != nil {
		t.Fatalf("AddEnum %s: %v", name, err)
	}
	if err := result.Apply(); err != nil {
		t.Fatalf("Apply add enum %s: %v", name, err)
	}
	return result
}

