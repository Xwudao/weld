package httpcontract

import (
	"bytes"
	_ "embed"
	"fmt"
	"go/format"
	"go/token"
	"sort"
	"strconv"
	"strings"
)

const ClientHeader = "// Code generated by weld client; DO NOT EDIT."

//go:embed client_runtime.go.tmpl
var clientRuntime string

//go:embed errors_runtime.go.tmpl
var errorsRuntime string

// Generate produces a standard-library-only client, with no server imports.
func Generate(c *Contract, packageName string) (map[string][]byte, error) {
	if err := c.Validate(); err != nil {
		return nil, err
	}
	if !token.IsIdentifier(packageName) || packageName == "_" || packageName == "main" {
		return nil, fmt.Errorf("invalid client package name %q", packageName)
	}
	var client strings.Builder
	client.WriteString(strings.Replace(clientRuntime, "package __package__", "package "+packageName, 1))
	for _, op := range c.Operations {
		name := GoName(op.Name)
		fmt.Fprintf(&client, "\n// %s calls %s %s.\nfunc (c *Client) %s(ctx context.Context", name, op.Method, op.Path, name)
		if op.Request != nil {
			fmt.Fprintf(&client, ", request %s", renderType(*op.Request))
		}
		if op.NoContent {
			client.WriteString(") error {\n")
		} else {
			fmt.Fprintf(&client, ") (%s, error) {\n var response %s\n", renderType(*op.Response), renderType(*op.Response))
		}
		fmt.Fprintf(&client, " info := requestInfo{operation:%q, method:%q, route:%q}\n path := info.route\n", op.Name, op.Method, op.Path)
		if op.Request != nil {
			fmt.Fprintf(&client, " var err error\n path, err = requestPath(path, request, %t)\n if err != nil {", op.Binding == "query")
			if op.NoContent {
				client.WriteString(" return info.requestError(\"bind\", err) ")
			} else {
				client.WriteString(" return response, info.requestError(\"bind\", err) ")
			}
			client.WriteString("}\n")
		}
		input := "nil"
		if op.Binding == "json" {
			input = "request"
		}
		if op.NoContent {
			fmt.Fprintf(&client, " return c.do(ctx, info, path, %s, nil, %d, true)\n}\n", input, op.Status)
		} else {
			fmt.Fprintf(&client, " errCall := c.do(ctx, info, path, %s, &response, %d, false)\n return response, errCall\n}\n", input, op.Status)
		}
	}
	clientCode, err := format.Source([]byte(client.String()))
	if err != nil {
		return nil, fmt.Errorf("format client: %w", err)
	}
	var dto bytes.Buffer
	fmt.Fprintf(&dto, "%s\n\npackage %s\n", ClientHeader, packageName)
	defs := append([]Definition(nil), c.Types...)
	sort.Slice(defs, func(i, j int) bool { return defs[i].Name < defs[j].Name })
	imports := map[string]bool{}
	for _, d := range defs {
		if hasKind(d.Type, "time") {
			imports["time"] = true
		}
		if hasKind(d.Type, "raw") {
			imports["encoding/json"] = true
		}
	}
	var paths []string
	for path := range imports {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	for _, path := range paths {
		fmt.Fprintf(&dto, "\nimport %q\n", path)
	}
	for _, d := range defs {
		fmt.Fprintf(&dto, "\ntype %s %s\n", d.Name, renderType(d.Type))
		if d.Type.Kind == "enum" {
			dto.WriteString("\nconst (\n")
			for _, v := range d.Type.Values {
				fmt.Fprintf(&dto, "%s %s = %q\n", v.Name, d.Name, v.Value)
			}
			dto.WriteString(")\n")
		}
	}
	dtoCode, err := format.Source(dto.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format client DTOs: %w", err)
	}
	errorCode, err := format.Source([]byte(strings.Replace(errorsRuntime, "package __package__", "package "+packageName, 1)))
	if err != nil {
		return nil, fmt.Errorf("format client errors: %w", err)
	}
	files := map[string][]byte{"client_gen.go": clientCode, "types_gen.go": dtoCode, "errors_gen.go": errorCode}
	for _, d := range defs {
		if d.Type.Kind == "enum" {
			data, err := renderEnum(d, packageName)
			if err != nil {
				return nil, err
			}
			files[enumFileName(d)] = data
		}
	}
	return files, nil
}

func renderType(t Type) string {
	switch t.Kind {
	case "basic", "ref":
		return t.Name
	case "time":
		return "time.Time"
	case "raw":
		return "json.RawMessage"
	case "enum":
		return "string"
	case "array":
		return fmt.Sprintf("[%d]%s", t.Len, renderType(*t.Elem))
	case "pointer":
		return "*" + renderType(*t.Elem)
	case "slice":
		return "[]" + renderType(*t.Elem)
	case "map":
		key := "string"
		if t.Key != nil {
			key = renderType(*t.Key)
		}
		return "map[" + key + "]" + renderType(*t.Elem)
	case "struct":
		var b strings.Builder
		b.WriteString("struct {\n")
		for _, f := range t.Fields {
			if f.Embedded {
				fmt.Fprintf(&b, " %s", renderType(f.Type))
			} else {
				fmt.Fprintf(&b, " %s %s", f.Name, renderType(f.Type))
			}
			if f.Tag != "" {
				if strings.ContainsAny(f.Tag, "`\r\n") {
					fmt.Fprintf(&b, " %s", strconv.Quote(f.Tag))
				} else {
					fmt.Fprintf(&b, " `%s`", f.Tag)
				}
			}
			b.WriteByte('\n')
		}
		b.WriteByte('}')
		return b.String()
	}
	panic("validated contract contains unknown type")
}

func hasKind(t Type, kind string) bool {
	if t.Kind == kind {
		return true
	}
	if t.Key != nil && hasKind(*t.Key, kind) {
		return true
	}
	if t.Elem != nil && hasKind(*t.Elem, kind) {
		return true
	}
	for _, f := range t.Fields {
		if hasKind(f.Type, kind) {
			return true
		}
	}
	return false
}
