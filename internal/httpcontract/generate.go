package httpcontract

import (
	"bytes"
	_ "embed"
	"fmt"
	"go/format"
	"go/token"
	"sort"
	"strconv"
	"strings"
)

const ClientHeader = "// Code generated by weld client; DO NOT EDIT."

//go:embed client_runtime.go.tmpl
var clientRuntime string

// Generate produces a standard-library-only client, with no server imports.
func Generate(c *Contract, packageName string) (map[string][]byte, error) {
	if err := c.Validate(); err != nil {
		return nil, err
	}
	if !token.IsIdentifier(packageName) || packageName == "_" || packageName == "main" {
		return nil, fmt.Errorf("invalid client package name %q", packageName)
	}
	var client strings.Builder
	client.WriteString(strings.Replace(clientRuntime, "package __package__", "package "+packageName, 1))
	for _, op := range c.Operations {
		name := GoName(op.Name)
		fmt.Fprintf(&client, "\n// %s calls %s %s.\nfunc (c *Client) %s(ctx context.Context", name, op.Method, op.Path, name)
		if op.Request != nil {
			fmt.Fprintf(&client, ", request %s", renderType(*op.Request))
		}
		if op.NoContent {
			client.WriteString(") error {\n")
		} else {
			fmt.Fprintf(&client, ") (%s, error) {\n var response %s\n", renderType(*op.Response), renderType(*op.Response))
		}
		fmt.Fprintf(&client, " path := %q\n", op.Path)
		if op.Request != nil {
			fmt.Fprintf(&client, " var err error\n path, err = requestPath(path, request, %t)\n if err != nil {", op.Binding == "query")
			if op.NoContent {
				client.WriteString(" return err ")
			} else {
				client.WriteString(" return response, err ")
			}
			client.WriteString("}\n")
		}
		input := "nil"
		if op.Binding == "json" {
			input = "request"
		}
		if op.NoContent {
			fmt.Fprintf(&client, " return c.do(ctx, %q, path, %s, nil, %d, true)\n}\n", op.Method, input, op.Status)
		} else {
			fmt.Fprintf(&client, " errCall := c.do(ctx, %q, path, %s, &response, %d, false)\n return response, errCall\n}\n", op.Method, input, op.Status)
		}
	}
	clientCode, err := format.Source([]byte(client.String()))
	if err != nil {
		return nil, fmt.Errorf("format client: %w", err)
	}
	var dto bytes.Buffer
	fmt.Fprintf(&dto, "%s\n\npackage %s\n", ClientHeader, packageName)
	defs := append([]Definition(nil), c.Types...)
	sort.Slice(defs, func(i, j int) bool { return defs[i].Name < defs[j].Name })
	for _, d := range defs {
		if hasTime(d.Type) {
			dto.WriteString("\nimport \"time\"\n")
			break
		}
	}
	for _, d := range defs {
		fmt.Fprintf(&dto, "\ntype %s %s\n", d.Name, renderType(d.Type))
	}
	dtoCode, err := format.Source(dto.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format client DTOs: %w", err)
	}
	return map[string][]byte{"client_gen.go": clientCode, "types_gen.go": dtoCode}, nil
}

func renderType(t Type) string {
	switch t.Kind {
	case "basic", "ref":
		return t.Name
	case "time":
		return "time.Time"
	case "pointer":
		return "*" + renderType(*t.Elem)
	case "slice":
		return "[]" + renderType(*t.Elem)
	case "map":
		return "map[string]" + renderType(*t.Elem)
	case "struct":
		var b strings.Builder
		b.WriteString("struct {\n")
		for _, f := range t.Fields {
			fmt.Fprintf(&b, " %s %s", f.Name, renderType(f.Type))
			if f.Tag != "" {
				if strings.ContainsAny(f.Tag, "`\r\n") {
					fmt.Fprintf(&b, " %s", strconv.Quote(f.Tag))
				} else {
					fmt.Fprintf(&b, " `%s`", f.Tag)
				}
			}
			b.WriteByte('\n')
		}
		b.WriteByte('}')
		return b.String()
	}
	panic("validated contract contains unknown type")
}

func hasTime(t Type) bool {
	if t.Kind == "time" {
		return true
	}
	if t.Elem != nil && hasTime(*t.Elem) {
		return true
	}
	for _, f := range t.Fields {
		if hasTime(f.Type) {
			return true
		}
	}
	return false
}
