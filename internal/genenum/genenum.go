// Package genenum detects Go string enumerations from source and renders the
// derived methods for each.
//
// An enum is a named type whose underlying type is string plus at least one
// constant of that type declared in the same package. The type and its constants
// are the source of truth and live in a hand-owned file; genenum renders the
// methods (String, values, Parse, the text and SQL codecs) into a sibling
// *_gen.go that the generator owns and rewrites.
//
// Detection uses the standard library's go/parser and go/ast only: no type
// checker, no external code generator, no magic comment. The convention is the
// shape the weld template emits — each constant carries the enum type (or
// inherits it within the same const block) and a distinct string literal.
package genenum

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"unicode"
)

// Header is the first line of every generated enum file. It marks the file as
// tool-owned (regenerated by `weld gen enum`) and is checked before a file is
// overwritten.
const Header = "// Code generated by weld gen enum; DO NOT EDIT."

// Value is one enum constant.
type Value struct {
	// Const is the constant identifier, for example StatusDraft.
	Const string
	// Raw is the string literal the constant is assigned when it is a plain
	// literal, otherwise "". It is used for duplicate detection; rendering
	// references the constant, so an unusual expression still generates.
	Raw string
}

// Enum is one detected enum type.
type Enum struct {
	// Name is the type name, for example Status.
	Name string
	// File is the source file that declares the type, for example status.go.
	File string
	// Values are the enum's constants in declaration order.
	Values []Value
}

// Package is one parsed Go package and the enums it declares.
type Package struct {
	// Name is the package clause shared by every file.
	Name string
	// Enums are the detected enums in type-declaration order.
	Enums []Enum
}

// Source is one package file to parse. Path is the file's base name.
type Source struct {
	Path    string
	Content []byte
}

// LoadDir reads and detects the enums in the Go package at dir. It excludes
// *_gen.go files, which are output, not source. A missing directory is not an
// error: it reports a nil package, so a project without an enum package is a
// no-op rather than a failure.
func LoadDir(dir string) (*Package, error) {
	return LoadDirOverlay(dir, nil)
}

// LoadDirOverlay is LoadDir with an in-memory overlay: each overlay entry is a
// base file name whose content replaces (or adds to) the file on disk. It lets
// a planner detect an enum from a file it has planned but not yet written.
func LoadDirOverlay(dir string, overlay map[string][]byte) (*Package, error) {
	files := map[string][]byte{}
	entries, err := os.ReadDir(dir)
	switch {
	case err == nil:
		for _, entry := range entries {
			name := entry.Name()
			if entry.IsDir() || !isSourceName(name) {
				continue
			}
			raw, err := os.ReadFile(filepath.Join(dir, name))
			if err != nil {
				return nil, err
			}
			files[name] = raw
		}
	case errors.Is(err, os.ErrNotExist):
		if len(overlay) == 0 {
			return nil, nil
		}
	default:
		return nil, err
	}
	for name, content := range overlay {
		if isSourceName(name) {
			files[name] = content
		}
	}
	if len(files) == 0 {
		return &Package{Name: "enums"}, nil
	}
	names := make([]string, 0, len(files))
	for name := range files {
		names = append(names, name)
	}
	sort.Strings(names)
	sources := make([]Source, 0, len(names))
	for _, name := range names {
		sources = append(sources, Source{Path: name, Content: files[name]})
	}
	return Detect(sources)
}

// isSourceName reports whether name is a hand-written Go source file: a file
// that ends in .go but is not generated output.
func isSourceName(name string) bool {
	return strings.HasSuffix(name, ".go") && !strings.HasSuffix(name, "_gen.go")
}

// Detect parses sources and returns the enums they declare.
//
// A file that does not parse is an error, so a syntax error is reported rather
// than silently producing an incomplete enum. Files may be supplied in any
// order; they are sorted by path so the result is deterministic.
func Detect(sources []Source) (*Package, error) {
	sorted := append([]Source(nil), sources...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Path < sorted[j].Path })

	fset := token.NewFileSet()
	parsed := make([]*ast.File, len(sorted))
	pkgName := ""
	for i, src := range sorted {
		file, err := parser.ParseFile(fset, src.Path, src.Content, 0)
		if err != nil {
			return nil, fmt.Errorf("parse %s: %w", src.Path, err)
		}
		parsed[i] = file
		if pkgName == "" {
			pkgName = file.Name.Name
		} else if pkgName != file.Name.Name {
			return nil, fmt.Errorf("mixed package names: %s declares %s, want %s", src.Path, file.Name.Name, pkgName)
		}
	}

	// Pass one: the named string types, in declaration order. The order is the
	// order the generated files are reported in.
	declared := map[string]string{} // type name -> declaring file
	var order []string
	for i, file := range parsed {
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.TYPE {
				continue
			}
			for _, spec := range gen.Specs {
				ts, ok := spec.(*ast.TypeSpec)
				if !ok || ts.Assign.IsValid() {
					continue
				}
				ident, ok := ts.Type.(*ast.Ident)
				if !ok || ident.Name != "string" {
					continue
				}
				if _, seen := declared[ts.Name.Name]; seen {
					continue
				}
				declared[ts.Name.Name] = sorted[i].Path
				order = append(order, ts.Name.Name)
			}
		}
	}

	// Pass two: the constants of each string type. A constant without its own
	// type inherits the previous spec's type within the same const block; a
	// constant with neither a new type nor a value repeats the previous value
	// and is an alias, so it is skipped rather than rendered twice.
	values := map[string][]Value{}
	for _, file := range parsed {
		for _, decl := range file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.CONST {
				continue
			}
			current := ""
			for _, spec := range gen.Specs {
				vs, ok := spec.(*ast.ValueSpec)
				if !ok {
					continue
				}
				if vs.Type != nil {
					if ident, ok := vs.Type.(*ast.Ident); ok {
						current = ident.Name
					} else {
						current = ""
					}
				}
				if _, isEnum := declared[current]; !isEnum {
					continue
				}
				if len(vs.Values) == 0 {
					continue
				}
				for j, name := range vs.Names {
					if name.Name == "_" || j >= len(vs.Values) {
						continue
					}
					values[current] = append(values[current], Value{Const: name.Name, Raw: stringLiteral(vs.Values[j])})
				}
			}
		}
	}

	pkg := &Package{Name: pkgName}
	for _, name := range order {
		if len(values[name]) == 0 {
			continue
		}
		pkg.Enums = append(pkg.Enums, Enum{Name: name, File: declared[name], Values: values[name]})
	}
	return pkg, nil
}

// stringLiteral returns the unquoted value of a string literal, or "" when the
// expression is not a plain string literal.
func stringLiteral(expr ast.Expr) string {
	lit, ok := expr.(*ast.BasicLit)
	if !ok || lit.Kind != token.STRING {
		return ""
	}
	unquoted, err := strconv.Unquote(lit.Value)
	if err != nil {
		return ""
	}
	return unquoted
}

// FileName returns the generated file's base name for an enum, derived from the
// type name so it is stable and collision-free: Status -> status_gen.go,
// OrderStatus -> order_status_gen.go.
func FileName(e Enum) string {
	return snake(e.Name) + "_gen.go"
}

// IsGenerated reports whether content is a file this generator owns.
func IsGenerated(content []byte) bool {
	return bytes.HasPrefix(content, []byte(Header))
}

// Render returns the gofmt-formatted *_gen.go source for e.
func Render(pkg *Package, e Enum) ([]byte, error) {
	name := e.Name
	lower := strings.ToLower(name[:1]) + name[1:]

	var b strings.Builder
	fmt.Fprintf(&b, "%s\n//\n// Source: %s. Regenerate with `weld gen enum`; edit %s, not this file.\n\n", Header, e.File, e.File)
	fmt.Fprintf(&b, "package %s\n\n", pkg.Name)
	b.WriteString("import (\n\t\"database/sql/driver\"\n\t\"fmt\"\n\t\"strings\"\n)\n\n")

	fmt.Fprintf(&b, "// String returns the wire value of v.\nfunc (v %s) String() string {\n\treturn string(v)\n}\n\n", name)

	fmt.Fprintf(&b, "// %sValues returns every %s in declaration order.\nfunc %sValues() []%s {\n\treturn []%s{\n", name, name, name, name, name)
	for _, v := range e.Values {
		fmt.Fprintf(&b, "\t\t%s,\n", v.Const)
	}
	b.WriteString("\t}\n}\n\n")

	fmt.Fprintf(&b, "// %sNames returns every %s wire value in declaration order.\nfunc %sNames() []string {\n\treturn []string{\n", name, name, name)
	for _, v := range e.Values {
		fmt.Fprintf(&b, "\t\tstring(%s),\n", v.Const)
	}
	b.WriteString("\t}\n}\n\n")

	fmt.Fprintf(&b, "var _%sByName = map[string]%s{\n", lower, name)
	for _, v := range e.Values {
		fmt.Fprintf(&b, "\tstring(%s): %s,\n", v.Const, v.Const)
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(&b, "// Parse%s parses raw as one of the declared %s values.\n//\n// It is exact and case-sensitive: an unknown value is an error, not a zero\n// value, so a typo fails closed.\nfunc Parse%s(raw string) (%s, error) {\n\tif value, ok := _%sByName[raw]; ok {\n\t\treturn value, nil\n\t}\n\treturn \"\", fmt.Errorf(\"invalid %s %%q: want one of %%s\", raw, strings.Join(%sNames(), \", \"))\n}\n\n", name, name, name, name, lower, name, name)

	fmt.Fprintf(&b, "// IsValid reports whether v is one of the declared %s values.\nfunc (v %s) IsValid() bool {\n\t_, ok := _%sByName[string(v)]\n\treturn ok\n}\n\n", name, name, lower)

	fmt.Fprintf(&b, "// MarshalText implements encoding.TextMarshaler, so the value serializes as\n// its wire string in JSON, YAML and any text protocol.\nfunc (v %s) MarshalText() ([]byte, error) {\n\treturn []byte(string(v)), nil\n}\n\n", name)

	fmt.Fprintf(&b, "// UnmarshalText implements encoding.TextUnmarshaler. An unknown value is an\n// error, so decoding a bad JSON or YAML value fails closed.\nfunc (v *%s) UnmarshalText(text []byte) error {\n\tparsed, err := Parse%s(string(text))\n\tif err != nil {\n\t\treturn err\n\t}\n\t*v = parsed\n\treturn nil\n}\n\n", name, name)

	fmt.Fprintf(&b, "// AppendText implements encoding.TextAppender.\nfunc (v %s) AppendText(b []byte) ([]byte, error) {\n\treturn append(b, string(v)...), nil\n}\n\n", name)

	fmt.Fprintf(&b, "// Value implements driver.Valuer for database/sql, storing the wire string.\nfunc (v %s) Value() (driver.Value, error) {\n\treturn string(v), nil\n}\n\n", name)

	fmt.Fprintf(&b, "// Scan implements sql.Scanner, accepting a string or []byte and rejecting an\n// unknown value. NULL scans to the unset zero value.\nfunc (v *%s) Scan(src any) error {\n\tswitch raw := src.(type) {\n\tcase nil:\n\t\t*v = \"\"\n\t\treturn nil\n\tcase string:\n\t\treturn v.UnmarshalText([]byte(raw))\n\tcase []byte:\n\t\treturn v.UnmarshalText(raw)\n\tdefault:\n\t\treturn fmt.Errorf(\"cannot scan %%T into %s\", src)\n\t}\n}\n", name, name)

	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("format generated %s: %w", FileName(e), err)
	}
	return formatted, nil
}

// snake converts an exported identifier to lower_snake_case: Status ->
// status, OrderStatus -> order_status.
func snake(name string) string {
	var b strings.Builder
	for i, r := range name {
		if i > 0 && unicode.IsUpper(r) {
			b.WriteByte('_')
		}
		b.WriteRune(unicode.ToLower(r))
	}
	return b.String()
}
