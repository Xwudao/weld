// Package sqlcx holds the descriptor contract test for the sqlcx capability.
// The payloads under files/ are templates for a generated project; this test
// guards the pins and markers that tie them to the db capability.
package sqlcx

import (
	"io/fs"
	"regexp"
	"strings"
	"testing"

	weldtemplate "github.com/Xwudao/weld/internal/weldtemplate"
)

func read(t *testing.T, name string) string {
	t.Helper()
	raw, err := fs.ReadFile(weldtemplate.FS(), name)
	if err != nil {
		t.Fatalf("read %s: %v", name, err)
	}
	return string(raw)
}

var sqlcPin = regexp.MustCompile(`(?m)^\s*github\.com/sqlc-dev/sqlc (v\S+)`)

// TestToolsModulePinsTheSameSQLC proves tools/sqlcx drives the sqlc release
// db/tools pins: the committed internal/data/sqlc files carry that version, so
// generating through sqlc-dynamic with another release would rewrite them.
func TestToolsModulePinsTheSameSQLC(t *testing.T) {
	pins := map[string]string{}
	for _, name := range []string{"capabilities/db/files/tools/go.mod.tmpl", "capabilities/sqlcx/files/tools/go.mod.tmpl"} {
		match := sqlcPin.FindStringSubmatch(read(t, name))
		if match == nil {
			t.Fatalf("%s does not pin github.com/sqlc-dev/sqlc", name)
		}
		pins[name] = match[1]
	}
	if db, sqlcx := pins["capabilities/db/files/tools/go.mod.tmpl"], pins["capabilities/sqlcx/files/tools/go.mod.tmpl"]; db != sqlcx {
		t.Fatalf("db/tools pins sqlc %s but tools/sqlcx pins %s; bump both together", db, sqlcx)
	}
	if generated := read(t, "capabilities/db/files/sqlc/db.go.tmpl"); !strings.Contains(generated, "sqlc "+pins["capabilities/db/files/tools/go.mod.tmpl"]) {
		t.Fatal("the shipped internal/data/sqlc code was generated by another sqlc release")
	}
}

// TestRuntimeAndToolVersionsMatch proves the application requires the same
// go-sqlcx release whose sqlc-dynamic generates the code it compiles.
func TestRuntimeAndToolVersionsMatch(t *testing.T) {
	pin := regexp.MustCompile(`github\.com/Xwudao/go-sqlcx (v\S+)`)
	app := pin.FindStringSubmatch(read(t, "capabilities/sqlcx/files/go.mod.snippet"))
	tool := pin.FindStringSubmatch(read(t, "capabilities/sqlcx/files/tools/go.mod.tmpl"))
	if app == nil || tool == nil || app[1] != tool[1] {
		t.Fatalf("go.mod snippet requires %v but tools/sqlcx pins %v", app, tool)
	}
}

// TestPatchesTheDBExtensionPoints proves every marker the sqlcx descriptor
// patches exists in the payload that ships the file.
func TestPatchesTheDBExtensionPoints(t *testing.T) {
	for file, markers := range map[string][]string{
		"capabilities/db/files/sqlc.yaml":     {"sqlcplugins", "sqlccodegen"},
		"capabilities/base/files/go.mod.tmpl": {"goversion", "deps"},
	} {
		content := read(t, file)
		for _, marker := range markers {
			for _, edge := range []string{"begin", "end"} {
				if !strings.Contains(content, "weld:"+marker+":"+edge) {
					t.Errorf("%s has no weld:%s:%s", file, marker, edge)
				}
			}
		}
	}
	if !strings.Contains(read(t, "capabilities/db/files/Makefile.snippet"), "\t$(SQLC_GENERATE)") {
		t.Error("the db Makefile sqlc recipe does not run $(SQLC_GENERATE), so sqlcx cannot switch it")
	}
	if !strings.Contains(read(t, "capabilities/sqlcx/files/Makefile.snippet"), "SQLC_GENERATE = cd tools/sqlcx && go tool sqlc-dynamic generate") {
		t.Error("the sqlcx Makefile snippet does not switch SQLC_GENERATE")
	}
}
